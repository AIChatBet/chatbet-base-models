"""Build the catalog and default policy from the channel's registry.

The channel's ``Registry`` is read by attribute only, so this module never
imports the channel. The catalog is generated from the code rather than typed by
hand, because a hand-written copy would drift the first time a step changes.
"""
from __future__ import annotations

import pprint
from collections.abc import Iterable
from typing import Any

from .catalog import (
    CapabilityDef,
    FactDef,
    FlowCatalog,
    FlowDef,
    FlowRef,
    OutcomeDef,
    StepDef,
    StrategyDef,
)
from .policy import FlowPolicy

CATALOG_KINDS = ("facts", "steps", "capabilities", "strategies", "flows")
GENERATED_HEADER = (
    '"""Generated by scripts/extract_flow_catalog.py from the channel registry.\n\n'
    "Do not edit by hand: regenerate it.\n"
    '"""\n\n'
)


def catalog_from_registry(registry: Any) -> FlowCatalog:
    return FlowCatalog(
        facts={name: _fact(fact) for name, fact in registry.facts.items()},
        steps={name: StepDef(**_contract(step)) for name, step in registry.steps.items()},
        capabilities={
            name: CapabilityDef(**_contract(capability))
            for name, capability in registry.capabilities_.items()
        },
        strategies={name: _strategy(strategy) for name, strategy in registry.strategies.items()},
        flows={name: _flow(flow) for name, flow in registry.flows.items()},
    )


def policy_from_registry(registry: Any) -> FlowPolicy:
    """The decisions the code already encoded, as the starting policy.

    A name the code marks ``omittable = False`` becomes required in every seed
    flow that lists it. That is exactly what the channel enforced, no more.
    """
    required: dict[str, tuple[str, ...]] = {}
    default_flows: dict[str, tuple[str, ...]] = {}
    for flow in registry.flows.values():
        names = tuple(ref.name for ref in flow.steps)
        default_flows[flow.id] = names
        locked = tuple(name for name in names if not _omittable(registry, name))
        if locked:
            required[flow.id] = locked
    return FlowPolicy(required_steps=required, default_flows=default_flows)


def catalog_drift(expected: FlowCatalog, actual: FlowCatalog) -> list[str]:
    """How the shipped catalog (``expected``) differs from the code (``actual``).

    Empty means in sync. Written for a CI failure message: it says which name and
    in which direction, not a wall of model diff.
    """
    drift: list[str] = []
    for kind in CATALOG_KINDS:
        shipped = getattr(expected, kind)
        in_code = getattr(actual, kind)
        for key in sorted(in_code.keys() - shipped.keys()):
            drift.append(f"{kind}: {key!r} exists in the code but not in the catalog")
        for key in sorted(shipped.keys() - in_code.keys()):
            drift.append(f"{kind}: {key!r} is in the catalog but not in the code")
        for key in sorted(shipped.keys() & in_code.keys()):
            if shipped[key] != in_code[key]:
                drift.append(f"{kind}: {key!r} differs between code and catalog")
    return drift


def render_generated_module(catalog: FlowCatalog, policy: FlowPolicy) -> str:
    """Python source holding the catalog and policy as plain data."""
    catalog_data = pprint.pformat(catalog.model_dump(mode="json"), width=100, sort_dicts=True)
    policy_data = pprint.pformat(policy.model_dump(mode="json"), width=100, sort_dicts=True)
    return f"{GENERATED_HEADER}CATALOG_DATA = {catalog_data}\n\nPOLICY_DATA = {policy_data}\n"


# --- helpers --------------------------------------------------------------------


def _fact(fact: Any) -> FactDef:
    return FactDef(name=fact.name, scope=getattr(fact.scope, "value", fact.scope))


def _copy_ids(messages: Iterable[Any]) -> tuple[str, ...]:
    """Every copy id a group of messages can display, sorted and deduplicated.

    ``Message.templates`` already leaves out literal text and literal option
    labels, which are data, not copy an operator owes.
    """
    ids: set[str] = set()
    for message in messages:
        ids |= set(message.templates)
    return tuple(sorted(ids))


def _outcomes(owner: Any) -> tuple[OutcomeDef, ...]:
    return tuple(
        OutcomeDef(id=outcome.id, renders=_copy_ids(outcome.renders))
        for outcome in getattr(owner, "outcomes", ())
    )


def _contract(owner: Any) -> dict[str, Any]:
    return {
        "id": owner.id,
        "requires": tuple(owner.requires),
        "provides": tuple(owner.provides),
        "renders": _copy_ids(getattr(owner, "renders", ())),
        "outcomes": _outcomes(owner),
    }


def _strategy(strategy: Any) -> StrategyDef:
    return StrategyDef(
        id=strategy.id,
        capability=strategy.capability,
        renders=_copy_ids(getattr(strategy, "renders", ())),
        outcomes=_outcomes(strategy),
    )


def _flow(flow: Any) -> FlowDef:
    return FlowDef(
        id=flow.id,
        steps=tuple(FlowRef(name=ref.name, kind=ref.kind) for ref in flow.steps),
    )


def _omittable(registry: Any, name: str) -> bool:
    contract = registry.steps.get(name) or registry.capabilities_.get(name)
    return True if contract is None else bool(getattr(contract, "omittable", True))
